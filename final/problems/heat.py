# Import the new utilities
from utils.plot_utils import plot_matrices_for_web, fig_to_base64_str
from utils.mesh_utils import generate_random_stone_mesh
from skfem import MeshTri, Basis, asm, enforce, BilinearForm, condense
from skfem.mesh import MeshTri


def solve_heat_for_web(mesh_type='rectangle', mesh_resolution_hint=None, kappa_val=None,
                       t_end_val=0.5, dt_val=0.01, theta_val=0.7):
    """
    Solve transient heat conduction using a generalized trapezoidal rule (theta method).
    Returns final temperature and plots as base64 strings for web display.
    """
    generated_plots = []

    # --- Mesh selection ---
    if mesh_type == 'random':
        # generate_random_stone_mesh will pick its own details
        print(f"[HEAT] Random mesh type to be generated by generate_random_stone_mesh(). Specified res hint: {mesh_resolution_hint}")
        mesh = generate_random_stone_mesh()
    elif mesh_type == 'circle':
        print(f"[HEAT] Using built-in circular mesh. Specified res hint: {mesh_resolution_hint}")
        # Use skfem's built-in circle mesh
        nrefs = mesh_resolution_hint if mesh_resolution_hint is not None else 3
        mesh = MeshTri.init_circle(nrefs)
    elif mesh_type == 'rectangle':
        print(f"[HEAT] Using built-in rectangular mesh. Specified res hint: {mesh_resolution_hint}")
        # Use skfem's built-in square mesh (default is unit square)
        nrefs = mesh_resolution_hint if mesh_resolution_hint is not None else 3
        # Create a square mesh and refine it
        mesh = MeshTri().refined(nrefs)
    elif mesh_type == 'lshaped':
        print(f"[HEAT] Using L-shaped domain mesh. Res hint: {mesh_resolution_hint}")
        # Initialize L-shaped domain mesh
        mesh = MeshTri.init_lshaped()
        # Refine if needed
        if mesh_resolution_hint is not None and mesh_resolution_hint > 0:
            mesh = mesh.refined(mesh_resolution_hint)
    elif mesh_type == 'symmetric':
        print(f"[HEAT] Using symmetric square mesh. Res hint: {mesh_resolution_hint}")
        # Initialize the symmetric mesh of unit square
        mesh = MeshTri.init_symmetric()
        # Refine if needed
        if mesh_resolution_hint is not None and mesh_resolution_hint > 0:
            mesh = mesh.refined(mesh_resolution_hint)
    elif mesh_type == 'sqsymmetric':
        print(f"[HEAT] Using square symmetric mesh. Res hint: {mesh_resolution_hint}")
        # Initialize another variant of symmetric mesh
        mesh = MeshTri.init_sqsymmetric()
        # Refine if needed
        if mesh_resolution_hint is not None and mesh_resolution_hint > 0:
            mesh = mesh.refined(mesh_resolution_hint)
    elif mesh_type == 'tensor':
        print(f"[HEAT] Using tensor product mesh. Res hint: {mesh_resolution_hint}")
        # Determine the resolution based on the hint
        n_points = max(3, mesh_resolution_hint if mesh_resolution_hint is not None else 10)
        # Create a tensor product mesh with specified points in each dimension
        x = np.linspace(0, 1, n_points)
        y = np.linspace(0, 1, n_points)
        mesh = MeshTri.init_tensor(x, y)
    else:
        raise ValueError(f"Invalid mesh_type: {mesh_type}. Use 'circle', 'rectangle', 'lshaped', 'symmetric', 'sqsymmetric', 'tensor', or 'random'.")

    basis = Basis(mesh, ElementTriP1(), intorder=2) # intorder=2 for P1 laplacian

    @BilinearForm
    def laplace(u, v, w):
        return dot(grad(u), grad(v))

    @BilinearForm
    def mass(u, v, w):
        return u * v

    K_stiffness = asm(laplace, basis) # Stiffness matrix K
    M_mass = asm(mass, basis)       # Mass matrix M

    # Define boundary DOFs. For ElementTriP1, mesh.boundary_nodes() gives the node indices.
    # basis.get_dofs() without arguments can be used if all DOFs on boundary elements are desired.
    # For P1 elements, basis.get_dofs(mesh.boundary_nodes()) is usually correct for Dirichlet.
    boundary_dofs = basis.get_dofs(mesh.boundary_nodes())

    # Apply zero Dirichlet boundary conditions using skfem.enforce
    # enforce modifies matrices to apply BCs, typically setting rows/cols to identity/zero.
    # K_bc = enforce(K_stiffness, D=boundary_dofs) # Modifies K
    # M_bc = enforce(M_mass, D=boundary_dofs)    # Modifies M
    # Note: enforce(..., D=dofs) zeros rows/cols and puts 1 on diag for 'dofs'.
    # This means the solution T at these DOFs will be forced to 0 if RHS for these DOFs is 0.

    # --- Time stepping parameters ---
    kappa_eff = kappa_val if kappa_val is not None else np.random.uniform(0.1, 2.0)
    t_end = t_end_val
    dt = dt_val
    theta = theta_val # 0: Explicit Euler, 0.5: Crank-Nicolson, 1: Implicit Euler
    n_steps = int(t_end / dt)

    print(f"[HEAT] Effective Params: Mesh Vertices: {mesh.p.shape[1]}, κ = {kappa_eff:.2f}, "
          f"t_end={t_end}, dt={dt}, theta={theta}")

    # --- Initial Condition T0 ---
    X_coords, Y_coords = basis.doflocs # Get coordinates of DOFs
    T_current = np.cos(np.pi * X_coords) * np.cos(np.pi * Y_coords)
    T_current[boundary_dofs] = 0.0 # Enforce BC on initial condition

    # 1. Plot Initial Temperature
    fig_initial_T, ax_initial_T = plt.subplots(figsize=(8, 6))
    tri_viz = mtri.Triangulation(mesh.p[0, :], mesh.p[1, :], mesh.t.T)
    contour_initial = ax_initial_T.tricontourf(tri_viz, T_current, cmap='coolwarm', levels=20)
    fig_initial_T.colorbar(contour_initial, ax=ax_initial_T, label="Initial Temperature T(0)")
    ax_initial_T.set_title("Initial Temperature Field at t=0")
    ax_initial_T.set_xlabel("X-coordinate")
    ax_initial_T.set_ylabel("Y-coordinate")
    ax_initial_T.set_aspect('equal', adjustable='box')
    generated_plots.append(fig_to_base64_str(fig_initial_T))


    # System matrices for time stepping: (M + θΔtκK)T_n+1 = (M - (1-θ)ΔtκK)T_n
    # Let LHS_matrix = M + θΔtκK
    # Let RHS_matrix_op = M - (1-θ)ΔtκK (this will be applied to T_n)

    # Apply BCs to K and M *before* forming time-stepping matrices
    # Important: create copies if K_stiffness/M_mass are reused, or use a method that doesn't modify in place
    # if that's desired. skfem.enforce typically modifies.
    # A common way is to use skfem.condense for the solve step, or ensure enforce works with the solver.
    
    # For time-dependent problems, enforce often sets Dofs to 0 and diag to 1.
    # K_bc, M_bc = K_stiffness.copy(), M_mass.copy() # Make copies to enforce on
    # K_bc = enforce(K_bc, D=boundary_dofs, x=np.zeros_like(boundary_dofs, dtype=float)) # x for non-zero values
    # M_bc = enforce(M_bc, D=boundary_dofs)
    # This approach with enforce needs careful check if it maintains symmetry for solver if K was symmetric.

    # Alternative using condense for each step (computationally more expensive)
    # Or, form A_time, B_time then condense A_time for factorization.
    
    LHS_matrix = M_mass + theta * dt * kappa_eff * K_stiffness
    RHS_matrix_op = M_mass - (1 - theta) * dt * kappa_eff * K_stiffness

    # 2. Plot matrices for time stepping (illustrative, before BCs for structure)
    # We plot LHS_matrix and for the "rhs vector" we can plot a representative application of RHS_matrix_op
    matrix_plot_strings = plot_matrices_for_web(
        LHS_matrix,
        RHS_matrix_op @ T_current, # Example RHS vector
        title_suffix="(Heat Eq. Time-Stepping Matrices)"
    )
    generated_plots.extend(matrix_plot_strings)

    # Factorize the (condensed) LHS matrix for solving in each time step
    # Condense incorporates the Dirichlet boundary conditions into the system.
    # LHS_condensed, _ = condense(LHS_matrix, np.zeros(basis.N), D=boundary_dofs) # RHS doesn't matter for matrix
    # splu expects CSC format.
    # A_factor = splu(LHS_condensed.tocsc())
    
    # Simpler: Factorize LHS_matrix and enforce BCs on solution T at each step.
    # This is valid if BCs are T=0. For non-zero, more care is needed.
    # For splu, it's better to condense first.
    
    # Let's try the explicit condensation approach for the solver:
    # We need to solve LHS_matrix * T_new = RHS_vector
    # where T_new[boundary_dofs] = 0.
    
    active_dofs = np.setdiff1d(np.arange(basis.N), boundary_dofs)
    
    # Condense the LHS matrix. The RHS vector will be formed and condensed each step.
    LHS_matrix_condensed, _ = condense(LHS_matrix, np.zeros(basis.N), D=boundary_dofs, expand=False)
    
    try:
        LHS_factor = splu(LHS_matrix_condensed.tocsc()) # Factorize the condensed LHS
    except RuntimeError as e: # Handle potential singularity if all DOFs are boundary
        print(f"Error during splu factorization: {e}. Mesh might be too coarse or all DOFs are boundary.")
        # Add a placeholder plot for error
        fig_err, ax_err = plt.subplots()
        ax_err.text(0.5, 0.5, "Error in factorization. Check mesh/BCs.", ha='center', va='center')
        generated_plots.append(fig_to_base64_str(fig_err))
        return mesh, basis, T_current, generated_plots


    print(f"[HEAT] Starting time stepping for {n_steps} steps...")
    for i in range(n_steps):
        # Calculate the full RHS vector: RHS_matrix_op @ T_current
        rhs_full = RHS_matrix_op @ T_current
        
        # Condense the RHS vector based on the boundary conditions
        # T_current already satisfies BCs. rhs_full needs to be condensed.
        _, rhs_condensed = condense(LHS_matrix, rhs_full, T_current, D=boundary_dofs, expand=False)
        # The T_current (x0) argument to condense here helps if BCs are non-zero,
        # for zero BCs, it ensures the RHS is adjusted correctly for the condensed system.

        # Solve for internal DOFs
        T_internal_new = LHS_factor.solve(rhs_condensed)
        
        # Update T_current: fill internal DOFs, boundary DOFs remain 0
        T_current = np.zeros(basis.N) # Ensure it's fresh for this step's solution
        T_current[active_dofs] = T_internal_new
        T_current[boundary_dofs] = 0.0 # Re-enforce just in case, should be handled by condense

        if (i + 1) % (n_steps // 10 or 1) == 0: # Print progress
            print(f"[HEAT] Time step {i+1}/{n_steps} completed. Max T: {T_current.max():.3f}")


    print(f"[HEAT] Max temperature at t={t_end:.2f}: {T_current.max():.3f}")

    # 3. Plot Final Temperature
    fig_final_T, ax_final_T = plt.subplots(figsize=(8, 6))
    contour_final = ax_final_T.tricontourf(tri_viz, T_current, cmap='hot', levels=20) # Use same tri_viz
    fig_final_T.colorbar(contour_final, ax=ax_final_T, label=f"Final Temperature T({t_end:.2f})")
    ax_final_T.set_title(f"Final Temperature Field at t={t_end:.2f}")
    ax_final_T.set_xlabel("X-coordinate")
    ax_final_T.set_ylabel("Y-coordinate")
    ax_final_T.set_aspect('equal', adjustable='box')
    generated_plots.append(fig_to_base64_str(fig_final_T))
    
    return mesh, basis, T_current, generated_plots