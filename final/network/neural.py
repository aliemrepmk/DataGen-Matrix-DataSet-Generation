def pyg_graph_to_scipy_sparse(graph_data: Data, value_to_fill: float = 1.0) -> scipy.sparse.csr_matrix:
    """
    Converts a PyTorch Geometric Data object to a SciPy CSR sparse matrix.
    Assumes edges are unweighted (i.e., graph_data.edge_attr is None or ignored)
    and fills existing edges in the sparse matrix with `value_to_fill`.

    Args:
        graph_data (Data): The PyTorch Geometric graph object.
                           It's expected to have `num_nodes` and `edge_index`.
        value_to_fill (float): The value to assign to existing edges in the sparse matrix.
                               Defaults to 1.0 for an unweighted adjacency matrix.

    Returns:
        scipy.sparse.csr_matrix: The sparse matrix representation of the graph.
    """
    num_nodes = graph_data.num_nodes

    if graph_data.edge_index is None or graph_data.edge_index.numel() == 0:
        return scipy.sparse.csr_matrix((num_nodes, num_nodes), dtype=np.float64 if isinstance(value_to_fill, float) else type(value_to_fill))

    edge_index = graph_data.edge_index.cpu().numpy()

    rows = edge_index[0]
    cols = edge_index[1]

    data_values = np.full(rows.shape[0], value_to_fill, dtype=type(value_to_fill))
    sparse_matrix = scipy.sparse.coo_matrix((data_values, (rows, cols)), shape=(num_nodes, num_nodes))

    return sparse_matrix.tocoo()

