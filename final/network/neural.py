"""**Model Training Loop**

Training process for the `AutoregressiveGraphGenerator`.

Key Steps:

1. _Hyperparameters & Setup_: Defines `LEARNING_RATE`, `EPOCHS`, and `DEVICE`. The models (already instantiated) are moved to the device. An Adam optimizer and BCEWithLogitsLoss (for binary edge prediction) are initialized. A `ReduceLROnPlateau` learning rate scheduler is also set up to adjust the learning rate if the loss plateaus.

2. _Training Mode_: The `autoregressive_generator` is set to `train()` mode.

3. _Epoch Loop_: Iterates for the specified number of `EPOCHS`.

4. _Graph Loop_: Iterates through each `original_full_graph_data` in the `graph_list` (loaded and processed earlier, with `batch_size=1` from the loader).

5. _Autoregressive Step Loop (Node-by-Node)_: For each graph, it iterates from the second node (`current_node_being_added_idx = 1`) up to the last node. In each step i:
  * _Partial Graph Extraction_: `extract_partial_graph`(`original_full_graph_data, i`) creates the input graph state, representing the graph built so far (nodes 0...i). This is the core of "true autoregressive" training.
  * _Model Prediction_: The `partial_graph_data_for_input` (as a Batch of one graph) and i are passed to `autoregressive_generator` to get `edge_logits` for connecting node i to nodes 0...i-1.
  * _Get True Targets_: `get_true_edges`(`original_full_graph_data, i`) fetches the ground truth edge connections for node i.
  * _Loss Calculation_: `BCEWithLogitsLoss` is computed between the predicted `edge_logits` and the `targets`.
  * _Loss Accumulation_: Loss for each step within a graph is accumulated.

6. _Backpropagation & Optimization_: After processing all nodes for a single graph, the accumulated (and averaged) loss for that graph is backpropagated. Gradient clipping is applied as a safeguard, and the optimizer takes a step.

7. _Logging & Scheduler_: The average loss per epoch is printed. The learning rate scheduler `scheduler.step()` is called with the epoch loss.

This loop trains the model to sequentially predict edge formations by showing it the correct partial graph state at each step and asking it to predict the next set of connections.
"""

LEARNING_RATE = 0.001
EPOCHS = 50

# Move the main generator model to the device
DEVICE = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
autoregressive_generator.to(DEVICE)

# Optimizer and Loss
optimizer = optim.Adam(autoregressive_generator.parameters(), lr=LEARNING_RATE)
criterion = nn.BCEWithLogitsLoss() # Binary Cross Entropy with Logits for edge prediction

# Learning rate scheduler: reduces LR if loss plateaus
scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(optimizer, 'min', factor=0.5, patience=5, verbose=True)

# Training Loop
print("\nStarting TRUE AUTOREGRESSIVE training...")
autoregressive_generator.train() # Set the model to training mode
best_epoch_loss = float('inf')
save_model_path = "network/trained_autoregressive_graph_generator.pth" # Define path to save model

for epoch in range(EPOCHS):
    epoch_total_loss = 0.0 # Accumulator for the total loss in this epoch
    total_predictions_in_epoch = 0 # Counter for the number of prediction steps made

    # Iterate through each graph in the dataset (via the DataLoader, which has batch_size=1)
    for graph_idx, original_full_graph_data_batch in enumerate(loader): # loader yields Batch objects
        # Since batch_size=1, original_full_graph_data_batch is a Batch object containing one graph.
        # We can directly use it or extract the single Data object if preferred,
        # but PyG Batch objects are designed to be processed directly by models.
        original_full_graph_data = original_full_graph_data_batch # Use the Batch object directly
        original_full_graph_data.to(DEVICE) # Ensure data is on the correct device

        num_nodes_in_full_graph = original_full_graph_data.num_nodes

        # Skip graphs with 0 or 1 node as no edges can be predicted for the first node's connections to predecessors
        if num_nodes_in_full_graph <= 1:
            continue

        graph_cumulative_loss = 0.0 # Accumulate loss for all steps in the current graph
        predictions_for_this_graph = 0 # Count prediction steps for this graph

        optimizer.zero_grad(set_to_none=True) # Zero gradients before processing a new graph sequence

        # Iterate through nodes to predict their connections to previous nodes
        # Node 0 is the starting point (implicitly added).
        # We start predicting for node 1 (its connection to node 0), then node 2 (to 0, 1), etc.
        for current_node_being_added_idx in range(1, num_nodes_in_full_graph):
            # Extract the partial graph: the graph built so far including the current node being added.
            # current_max_node_idx for extract_partial_graph is current_node_being_added_idx
            # as it includes nodes 0 up to current_node_being_added_idx.
            partial_graph_data_for_input = extract_partial_graph(original_full_graph_data, current_node_being_added_idx)
            # partial_graph_data_for_input is already on DEVICE if original_full_graph_data was.

            # Wrap the single partial graph Data object into a Batch object for the model.
            current_step_input_batch = Batch.from_data_list([partial_graph_data_for_input])

            # Get edge prediction logits from the model.
            # The model predicts connections for `current_node_being_added_idx`
            # to nodes `0, ..., current_node_being_added_idx - 1`.
            edge_logits = autoregressive_generator(current_step_input_batch, current_node_being_added_idx)

            # Get the true target edges for the current node.
            targets = get_true_edges(original_full_graph_data, current_node_being_added_idx)

            # Calculate loss for this prediction step.
            # Ensure shapes match: edge_logits is [1, N], targets is [N].
            if edge_logits.shape[0] == 1 and edge_logits.shape[1] == targets.shape[0]:
                loss = criterion(edge_logits.squeeze(0), targets.float()) # Squeeze batch dim from logits

                if not torch.isnan(loss) and not torch.isinf(loss):
                    graph_cumulative_loss += loss
                    predictions_for_this_graph += 1
                else:
                    print(f"Warning: NaN or Inf loss at graph {graph_idx}, node {current_node_being_added_idx}.")
            else:
                # This warning helps catch issues if slicing or target generation is off.
                print(f"Warning: Shape mismatch or empty targets/logits at graph {graph_idx}, node {current_node_being_added_idx}. Logits: {edge_logits.shape}, Targets: {targets.shape}")
                continue

        # After processing all nodes for the current graph, if any valid predictions were made:
        if predictions_for_this_graph > 0:
            average_loss_for_graph = graph_cumulative_loss / predictions_for_this_graph
            average_loss_for_graph.backward() # Backpropagate the accumulated loss for this graph's sequence.

            torch.nn.utils.clip_grad_norm_(autoregressive_generator.parameters(), max_norm=1.0) # Apply gradient clipping.
            optimizer.step() # Update model parameters.

            epoch_total_loss += average_loss_for_graph.item() * predictions_for_this_graph
            total_predictions_in_epoch += predictions_for_this_graph

    # After processing all graphs in the epoch:
    if total_predictions_in_epoch > 0:
        average_epoch_loss = epoch_total_loss / total_predictions_in_epoch
        print(f"Epoch {epoch+1}/{EPOCHS}, Average Loss: {average_epoch_loss:.4f}")

        # Save the model if this epoch has the best loss so far
        if average_epoch_loss < best_epoch_loss:
            best_epoch_loss = average_epoch_loss
            torch.save(autoregressive_generator.state_dict(), save_model_path)
            print(f"Model saved to {save_model_path} at epoch {epoch+1} with loss {best_epoch_loss:.4f}")

        if scheduler is not None:
            scheduler.step(average_epoch_loss)
    else:
        print(f"Epoch {epoch+1}/{EPOCHS}, No valid predictions made in this epoch.")

print("True autoregressive training finished.")

"""**Graph Generation (Inference) Function**

Here, we defined the `generate_graph` function, which uses the trained `AutoregressiveGraphGenerator` to produce new graph structures. This is the inference part of the model.

Key Steps:

1. _Setup_: The function is decorated with `@torch.no_grad()` to disable gradient calculations, and the model is set to `eval()` mode.

2. _Initialization_: An empty list `generated_edges_list` is created to store the edges of the graph being built. `current_num_nodes` starts at 1 (for the first implicit node).

3. _Iterative Node Addition_: The function loops from the second node (`new_node_idx = 1`) up to the desired `num_nodes_to_generate`.

4. _Prepare Current Graph State_: In each iteration i, a PyG Data object (`current_graph_data`) is created representing the graph built so far (nodes 0 to i-1 and their edges). This is wrapped in a Batch object.

5. _Predict Edge Logits_: The `current_graph_as_batch` and i (as `current_node_idx_in_graph`) are passed to the trained model to get `edge_logits` for connecting node i to all previous nodes.

6. _Sample Edges_: Logits are converted to probabilities using `torch.sigmoid`. Then, `torch.bernoulli` is used to stochastically decide which edges to add based on these probabilities.

7. _Add Edges_: If an edge is sampled, it's added (as an undirected pair) to `generated_edges_list`.

8. _Increment Node Count_: `current_num_nodes` is incremented.

9. _Final Graph Creation_: After the loop, a final PyG Data object is created using all `generated_edges_list` and the target `num_nodes_to_generate`. Utilities like coalesce and `remove_self_loops` are used to clean up the `edge_index`.

This function allows for sampling novel graph structures based on the patterns learned by the autoregressive model during training.
"""

@torch.no_grad() # Disable gradient calculations during inference
def generate_graph(model: AutoregressiveGraphGenerator,
                   num_nodes_to_generate: int,
                   device: torch.device,
                   sampling_threshold: float = 0.5) -> Data:
    """
    Generates a single graph using the trained autoregressive model with stochastic sampling.

    Args:
        model (AutoregressiveGraphGenerator): The trained model.
        num_nodes_to_generate (int): The total number of nodes the generated graph should have.
        device (torch.device): The device to run generation on (cpu or cuda).

    Returns:
        Data: A PyTorch Geometric Data object representing the generated graph.
    """
    model.eval() # Set the model to evaluation mode

    # Handle edge cases for num_nodes_to_generate
    if num_nodes_to_generate <= 0:
        return Data(num_nodes=0, edge_index=torch.empty((2,0), dtype=torch.long))
    if num_nodes_to_generate == 1: # A graph with 1 node has no edges
        return Data(num_nodes=1, edge_index=torch.empty((2,0), dtype=torch.long))

    # Initialize list to store edges of the graph being built
    generated_edges_list_tuples = set() # Use a set of tuples to store unique undirected edges
    current_num_nodes = 1 # Start with the first node (node 0) implicitly added

    # Loop to add nodes from the second node (index 1) up to num_nodes_to_generate
    for new_node_idx in range(1, num_nodes_to_generate):
        # Prepare the Data object for the current state of the graph (nodes 0 to current_num_nodes-1)
        if not generated_edges_list_tuples:
            current_edge_index = torch.empty((2, 0), dtype=torch.long, device=device)
        else:
            # Convert set of tuples to edge_index format
            edge_list_for_tensor = []
            for u, v in generated_edges_list_tuples:
                edge_list_for_tensor.append([u,v])
                edge_list_for_tensor.append([v,u]) # Add symmetric edge for undirected representation
            if not edge_list_for_tensor: # Check if list is empty before creating tensor
                 current_edge_index = torch.empty((2, 0), dtype=torch.long, device=device)
            else:
                 current_edge_index = torch.tensor(edge_list_for_tensor, dtype=torch.long, device=device).t().contiguous()
                 current_edge_index = coalesce(current_edge_index) # Ensure sorted and unique

        current_graph_data = Data(num_nodes=current_num_nodes, edge_index=current_edge_index).to(device)
        current_graph_as_batch = Batch.from_data_list([current_graph_data]) # Wrap in a Batch

        # Get edge prediction logits from the model for the new_node_idx
        edge_logits = model(current_graph_as_batch, new_node_idx) # Predicts connections to nodes 0..new_node_idx-1

        # Convert logits to probabilities
        edge_probs = torch.sigmoid(edge_logits.squeeze(0)) # Shape: [new_node_idx]

        # Sample edges stochastically using Bernoulli distribution
        edge_decisions = torch.bernoulli(edge_probs) # Tensor of 0s and 1s

        # Add edges based on sampled decisions
        for prev_node_idx in range(new_node_idx):
            # Stochastic sampling
            """
            if edge_decisions[prev_node_idx].item() == 1:
                # Add edge as a sorted tuple to handle undirected nature and avoid duplicates in the set
                u, v = min(new_node_idx, prev_node_idx), max(new_node_idx, prev_node_idx)
                generated_edges_list_tuples.add((u,v))
            """
            # Deterministic sampling
            if edge_probs[prev_node_idx] > sampling_threshold: # Deterministic check
              # Add undirected edge
              generated_edges_list_tuples.add((new_node_idx, prev_node_idx))
              generated_edges_list_tuples.add((prev_node_idx, new_node_idx))

        current_num_nodes += 1 # Increment node count for the next step

    # Create the final edge_index from the set of unique undirected edges
    if not generated_edges_list_tuples:
        final_edge_index = torch.empty((2,0), dtype=torch.long)
    else:
        final_edge_list_symmetric = []
        for u,v in generated_edges_list_tuples:
            final_edge_list_symmetric.append([u,v])
            final_edge_list_symmetric.append([v,u])
        if not final_edge_list_symmetric: # Should not happen if generated_edges_list_tuples was not empty
            final_edge_index = torch.empty((2,0), dtype=torch.long)
        else:
            final_edge_index = torch.tensor(final_edge_list_symmetric, dtype=torch.long).t().contiguous()
            final_edge_index = coalesce(final_edge_index) # Final cleanup: sort and remove duplicates

    # Create the final PyG Data object for the generated graph
    generated_graph = Data(num_nodes=num_nodes_to_generate,
                           edge_index=final_edge_index.to('cpu')) # Move final graph to CPU
    return generated_graph

